CREATE TABLE eleitor (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo   VARCHAR(12)  NOT NULL,
    nome     VARCHAR(120) NOT NULL,
    secao_id BIGINT       NOT NULL REFERENCES secao (id),
    CONSTRAINT uk_eleitor_titulo UNIQUE (titulo)
);

CREATE INDEX ix_eleitor_secao ON eleitor (secao_id);

CREATE TABLE urna (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    eleicao_id            BIGINT                   NOT NULL REFERENCES eleicao (id),
    secao_id              BIGINT                   NOT NULL REFERENCES secao (id),
    estado                VARCHAR(20)              NOT NULL,
    chave_publica         VARCHAR(200)             NOT NULL,
    eleitor_habilitado_id BIGINT REFERENCES eleitor (id),
    aberta_em             TIMESTAMP WITH TIME ZONE NOT NULL,
    encerrada_em          TIMESTAMP WITH TIME ZONE,
    bu_conteudo           CLOB,
    bu_assinatura         VARCHAR(200),
    versao                BIGINT DEFAULT 0         NOT NULL,
    CONSTRAINT uk_urna_secao UNIQUE (eleicao_id, secao_id)
);

-- Caderno de votação: registra QUEM votou, nunca EM QUEM.
CREATE TABLE comparecimento (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    urna_id    BIGINT NOT NULL REFERENCES urna (id),
    eleitor_id BIGINT NOT NULL REFERENCES eleitor (id),
    CONSTRAINT uk_comparecimento UNIQUE (urna_id, eleitor_id)
);

-- Registro Digital do Voto. Para preservar o sigilo, não tem id sequencial, horário
-- nem referência ao eleitor: cada voto ocupa uma posição sorteada, por cargo.
CREATE TABLE rdv_voto (
    urna_id BIGINT      NOT NULL REFERENCES urna (id),
    cargo   VARCHAR(20) NOT NULL,
    posicao INTEGER     NOT NULL,
    tipo    VARCHAR(10) NOT NULL,
    numero  VARCHAR(5),
    PRIMARY KEY (urna_id, cargo, posicao)
);

