CREATE TABLE eleicao (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(120) NOT NULL,
    ano       INTEGER      NOT NULL,
    turno     INTEGER      NOT NULL,
    CONSTRAINT uk_eleicao_ano_turno UNIQUE (ano, turno)
);

CREATE TABLE secao (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zona            INTEGER     NOT NULL,
    numero          INTEGER     NOT NULL,
    municipio       VARCHAR(80) NOT NULL,
    uf              VARCHAR(2)  NOT NULL,
    eleitores_aptos INTEGER     NOT NULL,
    CONSTRAINT uk_secao_zona_numero UNIQUE (zona, numero),
    CONSTRAINT ck_secao_aptos CHECK (eleitores_aptos > 0)
);

CREATE TABLE candidato (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    eleicao_id BIGINT       NOT NULL REFERENCES eleicao (id),
    cargo      VARCHAR(20)  NOT NULL,
    numero     VARCHAR(5)   NOT NULL,
    nome       VARCHAR(120) NOT NULL,
    partido    VARCHAR(10)  NOT NULL,
    CONSTRAINT uk_candidato_numero UNIQUE (eleicao_id, cargo, numero)
);

CREATE TABLE boletim_urna (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    eleicao_id     BIGINT                   NOT NULL REFERENCES eleicao (id),
    secao_id       BIGINT                   NOT NULL REFERENCES secao (id),
    comparecimento INTEGER                  NOT NULL,
    recebido_em    TIMESTAMP WITH TIME ZONE NOT NULL,
    -- Garante no banco a regra "um boletim por seção", mesmo com requisições concorrentes.
    CONSTRAINT uk_boletim_secao UNIQUE (eleicao_id, secao_id)
);

CREATE TABLE boletim_cargo (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    boletim_id BIGINT      NOT NULL REFERENCES boletim_urna (id),
    cargo      VARCHAR(20) NOT NULL,
    brancos    INTEGER     NOT NULL,
    nulos      INTEGER     NOT NULL,
    CONSTRAINT uk_boletim_cargo UNIQUE (boletim_id, cargo)
);

CREATE TABLE voto_candidato (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    boletim_id   BIGINT  NOT NULL REFERENCES boletim_urna (id),
    candidato_id BIGINT  NOT NULL REFERENCES candidato (id),
    votos        INTEGER NOT NULL,
    CONSTRAINT uk_voto_candidato UNIQUE (boletim_id, candidato_id)
);

CREATE INDEX ix_voto_candidato_candidato ON voto_candidato (candidato_id);
CREATE INDEX ix_boletim_cargo_cargo ON boletim_cargo (cargo);
